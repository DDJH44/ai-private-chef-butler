/** Classify an ingredient name → category string */
export function classifyIngredient(name: string): string {
  if (!name?.trim()) return "其他";
  const n = name.trim();

  for (const [keywords, category] of RULES) {
    if (keywords.some(kw => n.includes(kw))) {
      return category;
    }
  }
  return "其他";
}
